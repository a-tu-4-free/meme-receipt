/**
 * =========================
 * 🔧 TEMPLATE ENGINE
 * =========================
 */

export function fillTemplate(str) {
    if (!str) return "";

    return str
        .replace(/{days}/g, () => randRange(20, 820))
        .replace(/{money}/g, () => randRange(300, 5300) + "萬")
        .replace(/{num}/g, () => randRange(10000, 99999))
        .replace(/{year}/g, () => 2024 + randRange(0, 4));
}

